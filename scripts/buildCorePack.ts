let allPassed = true;

for (const level of levels) {
  const report = solveLevel(level, 10);
  if (!report.isSolvable) {
    console.error(`❌ Level ${level.id} ("${level.title}") is NOT solvable!`);
    allPassed = false;
  } else {
    console.log(
      `✅ Level ${level.id.toString().padStart(2, ' ')}: "${level.title}" (${level.arrows.length} arrows, ${level.width}x${level.height}) - Solvable! Solutions: ${report.totalSolutions}+, Difficulty: ${report.difficultyScore}`
    );
  }
}

if (!allPassed) {
  console.error('Validation failed. Aborting write.');
  process.exit(1);
}

